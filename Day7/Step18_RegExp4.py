import re

if __name__ == "__main__":
    # 1. 임의의 문자열을 입력 받는다.
    user_id = input("아이디를 입력(영문자 대소문자, 숫자만 가능): ")

    # 2. 정규표현식 패턴 설정
    # ^ : 시작, [a-zA-Z0-9] : 영문 대소문자와 숫자, + : 1글자 이상, $ : 끝
    # 즉, 처음부터 끝까지 영문자와 숫자로만 구성되어야 함
    pattern = r"[a-zA-Z0-9]{5,12}"

    # 3. 입력한 문자열 검증
    if re.search(pattern, user_id):
        print("✅ 가입되었습니다.")
    else:
        # 실패 시 구체적인 이유를 안내해주는 게 '친절한 에이스'의 센스죠!
        print("❌ 사용할 수 없는 아이디입니다.")
        print("   - 영문 대소문자와 숫자만 사용 가능")
        print("   - 길이는 5자 이상 12자 이하")